"""Generate TypeScript transport contracts directly from Pydantic JSON Schema.

Only imports the model module, never the application or runtime stores. Print to
stdout for regeneration; --check verifies the committed file without modifying it.
Serialized BaseModels include defaults; TypedDict optional keys remain optional.
Input aliases retain each request model's actual required/default distinction.
"""

import argparse
import json
from pathlib import Path
import sys

from pydantic import BaseModel, create_model

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "server_application/backend"))
from models import api_models as api
from src import domain

OUTPUT = ROOT / "frontend/auto-cv-customizer/src/types/api.generated.ts"
ROOT_MODELS = [
    api.CVJobResponse, api.ProcessingOutput, api.WorkingCopy, api.BackendConfig,
    api.CreateJobRequest, api.JobAnalysisRequest, api.JobAnalysisResponse,
    api.RenderCVRequest, api.RescoreRequest, api.RescoreResponse, api.Submission,
    api.SubmissionCreateRequest, api.SubmissionUpdateRequest, api.StreamError,
]


def ts_type(schema):
    if isinstance(schema, bool):
        return "unknown" if schema else "never"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "anyOf" in schema:
        return " | ".join(ts_type(part) for part in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        return f"Record<string, {ts_type(schema.get('additionalProperties', {}))}>"
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def generate():
    root = create_model("Transport", **{model.__name__: (model, ...) for model in ROOT_MODELS})
    definitions = root.model_json_schema(mode="serialization")["$defs"]
    model_names = {name for name, model in (vars(api) | vars(domain)).items()
                   if isinstance(model, type) and issubclass(model, BaseModel)}
    lines = ["// Generated by tools/generate_api_types.py; do not edit by hand.",
             "// Serialized API models include defaults; request Input aliases allow omission.", ""]
    for name, schema in sorted(definitions.items()):
        if "properties" not in schema:
            lines.extend([f"export type {name} = {ts_type(schema)};", ""])
            continue
        lines.append(f"export interface {name} {{")
        required = set(schema.get("required", []))
        if name in model_names:
            required = set(schema["properties"])
        for field, value in schema["properties"].items():
            optional = "" if field in required else "?"
            lines.append(f"  {field}{optional}: {ts_type(value)};")
        lines.extend(["}", ""])
    for model in ROOT_MODELS:
        if model.__name__.endswith("Request"):
            required = model.model_json_schema().get("required", [])
            keys = " | ".join(json.dumps(key) for key in required) or "never"
            lines.append(f"export type {model.__name__}Input = Partial<{model.__name__}> & Pick<{model.__name__}, {keys}>;")
    lines.extend(["", "export const DEFAULT_BACKEND_CONFIG: BackendConfig = " +
                  json.dumps(api.BackendConfig().model_dump(mode="json"), indent=2) + ";"])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit("Transport types are stale; regenerate with tools/generate_api_types.py")
        print("Transport types match Pydantic schemas.")
    else:
        print(generated, end="")


if __name__ == "__main__":
    main()
