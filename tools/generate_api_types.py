"""Generate TypeScript transport contracts directly from Pydantic JSON Schema.

Only imports the model module, never the application or runtime stores. Print to
stdout for regeneration; --check verifies the committed file without modifying it.
Serialized BaseModels include defaults; TypedDict optional keys remain optional.
Input aliases retain each request model's actual required/default distinction.
"""

import argparse
import json
from pathlib import Path

from pydantic import BaseModel, create_model

ROOT = Path(__file__).resolve().parents[1]
from server_application.backend.models import api_models as api
from src import domain
from src import composition, template_package
from server_application.backend.models import studio
from src.template_registry import TemplateRegistryResponse

OUTPUT = ROOT / "frontend/auto-cv-customizer/src/types/api.generated.ts"
ROOT_MODELS = [
    api.CVJobResponse, api.ProcessingOutput, api.WorkingCopy, api.BackendConfig,
    api.CreateJobRequest, api.JobAnalysisRequest, api.JobAnalysisResponse,
    api.RenderCVRequest, api.RescoreRequest, api.RescoreResponse, api.Submission,
    api.SubmissionCreateRequest, api.SubmissionUpdateRequest, api.StreamError, TemplateRegistryResponse,
    api.ProviderModelList, api.ModelCatalogResponse,
    template_package.TemplatePackage, template_package.TemplateRevision,
    studio.StudioImportRequest, studio.StudioDraft, studio.StudioSaveRequest,
    studio.StudioPreviewRequest, studio.StudioPreviewError, studio.StudioPreviewReport,
]


def ts_type(schema):
    if isinstance(schema, bool):
        return "unknown" if schema else "never"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "anyOf" in schema:
        return " | ".join(ts_type(part) for part in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(ts_type(part) for part in schema["oneOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        return f"Record<string, {ts_type(schema.get('additionalProperties', {}))}>"
    return {"string": "string", "integer": "number", "number": "number",
             "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def validator_dialect(schema):
    """Ajv infers literal-kind mappings from oneOf; OpenAPI's mapping is unsupported.

    The actual oneOf/$ref/const constraints are retained. This is a serialization
    adapter, not a handwritten second CV schema or disabled strict validation.
    """
    if isinstance(schema, dict):
        if 'discriminator' in schema:
            schema['discriminator'].pop('mapping', None)
            schema.setdefault('type', 'object')
        for value in schema.values():
            validator_dialect(value)
    elif isinstance(schema, list):
        for value in schema:
            validator_dialect(value)
    return schema


def generate():
    root = create_model("Transport", **{model.__name__: (model, ...) for model in ROOT_MODELS})
    definitions = root.model_json_schema(mode="serialization")["$defs"]
    models = vars(api) | vars(domain) | vars(composition) | vars(template_package) | vars(studio)
    model_names = {name for name, model in models.items()
                    if isinstance(model, type) and issubclass(model, BaseModel)}
    model_names.add('TemplateRegistryResponse')
    lines = ["// Generated by tools/generate_api_types.py; do not edit by hand.",
             "// Serialized API models include defaults; request Input aliases allow omission.", ""]
    for name, schema in sorted(definitions.items()):
        if "properties" not in schema:
            lines.extend([f"export type {name} = {ts_type(schema)};", ""])
            continue
        lines.append(f"export interface {name} {{")
        required = set(schema.get("required", []))
        if name in model_names:
            required = set(schema["properties"])
        for field, value in schema["properties"].items():
            optional = "" if field in required else "?"
            lines.append(f"  {field}{optional}: {ts_type(value)};")
        lines.extend(["}", ""])
    for model in ROOT_MODELS:
        if model.__name__.endswith("Request"):
            required = model.model_json_schema().get("required", [])
            keys = " | ".join(json.dumps(key) for key in required) or "never"
            lines.append(f"export type {model.__name__}Input = Partial<{model.__name__}> & Pick<{model.__name__}, {keys}>;")
    lines.extend(["", "export const DEFAULT_BACKEND_CONFIG: BackendConfig = " +
                   json.dumps(api.BackendConfig().model_dump(mode="json"), indent=2) + ";"])
    editable_schema = domain.CVData.model_json_schema()
    # Pydantic's schema omits default_factory values; include their real defaults
    # so JSON-to-visual editing receives the same complete value as an API read.
    for model in {model for model in models.values() if isinstance(model, type) and issubclass(model, BaseModel)
                  and (model is domain.CVData or model.__name__ in editable_schema['$defs'])}:
        schema = editable_schema if model is domain.CVData else editable_schema['$defs'][model.__name__]
        for name, field in model.model_fields.items():
            if not field.is_required():
                value = field.get_default(call_default_factory=True)
                schema['properties'][name]['default'] = value.model_dump(mode='json') if isinstance(value, BaseModel) else value
    lines.extend(["", "export const CV_DATA_SCHEMA = " + json.dumps(validator_dialect(editable_schema), indent=2) + " as const;"])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit("Transport types are stale; regenerate with tools/generate_api_types.py")
        print("Transport types match Pydantic schemas.")
    else:
        print(generated, end="")


if __name__ == "__main__":
    main()
